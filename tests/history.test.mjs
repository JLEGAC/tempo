import assert from 'node:assert/strict';
import { defaults, migrate, validateSettings } from '../dist/domain/settings.mjs';
import { fresh, total } from '../dist/domain/time.mjs';
import { balance } from '../dist/domain/balance.mjs';
import { realWeek, weekStats, habits, validWeek, backup, decodeBackup } from '../dist/domain/history.mjs';

const p = defaults(), rows = fresh(p), start = '2099-01-05';
let week = realWeek(rows, start, p.target);
assert.equal(weekStats(week).minutes, 0);
assert.equal(weekStats(week).complete, false);
assert.equal(habits(week), null);
assert(week.days.every(day => day.times.every(time => time === null)));
rows[0].real = [true, true, true, true];
rows[1].real = [true, true, true, false];
week = realWeek(rows, start, p.target);
assert(validWeek(week));
assert.equal(weekStats(week).minutes, 480 + 240);
assert.equal(habits(week).count, 1);
assert.equal(habits(week).arrival, 540);
assert.equal(habits(week).departure, 1050);
assert.equal(habits(week).lunch, 30);
rows.forEach(row => { row.real = [true, true, true, true]; });
const complete = realWeek(rows, start, 2400, week);
assert.equal(complete.target, 2280);
assert(weekStats(complete).complete);
assert.equal(weekStats(complete).minutes, 2310);
const saved = backup(p, [complete]);
const restored = decodeBackup(JSON.parse(JSON.stringify(saved)));
assert.deepEqual(restored.weeks, [complete]);
assert.deepEqual(restored.profile.priorities, p.priorities);
assert.deepEqual(decodeBackup({ ...p, version: 2 }).profile.priorities, ['departure', 'lunch', 'arrival']);
assert.throws(() => decodeBackup({ ...saved, weeks: [complete, complete] }), /doublon/);
assert.throws(() => decodeBackup({ ...saved, weeks: [{ ...complete, target: -10 }] }), /invalide/);
assert.throws(() => decodeBackup({ ...saved, profile: { ...p, priorities: ['departure', 'departure', 'lunch'] } }), /invalides/);
assert(!validateSettings({ ...p, priorities: ['arrival'] }));
const legacy = { ...p, version: 2, mode: 'arrival' };
assert.deepEqual(migrate(legacy).priorities, ['arrival', 'departure', 'lunch']);
// La deuxième préférence est utilisée avant la troisième.
const sample = fresh(p);
sample.forEach(row => { row.times[0] = '08:00'; });
const custom = { ...p, target: 2200, priorities: ['departure', 'arrival', 'lunch'] };
const adjusted = balance(sample, custom, start, new Date('2099-01-01T08:00:00'));
assert.equal(total(adjusted), 2200);
assert(adjusted.every(row => row.times[0] === '08:10'));
assert(adjusted.every(row => row.times[1] === '13:00' && row.times[2] === '13:30'));
console.log('Historique réel, incomplets, moyennes, sauvegarde, validation et ordre : OK.');
